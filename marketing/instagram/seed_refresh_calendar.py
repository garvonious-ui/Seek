#!/usr/bin/env python3
"""
Writes the ig_post_queue SQL for the Nov 30 - Dec 25 refresh.

  seed-refresh-weeks1-2.sql   time test (wk1 7:30am ET, wk2 7:30pm ET) + Thanksgiving bridge + Saturday prompts
  seed-refresh-weeks3-4.sql   run AFTER the test; pass the winning slot:
                              python3 seed_refresh_calendar.py am|pm

Every row is status='pending', so nothing posts until it's approved in the
dashboard. day_index continues from the current max in the table.
Captions use one fixed template during the test so the only thing that
changes between week 1 and week 2 is the posting time.

Media must be uploaded to the ig-media bucket first, keeping these paths:
  reels-refresh/<id>.mp4
  carousels-refresh/<carousel id>/<carousel id>_feed_<n>.png   (+ _story_0.png)
"""
import sys, datetime as dt
from refresh_slate import SLATE, CAROUSELS, HASHTAGS, CTA

# Dec 2026 is EST (UTC-5). 7:30am ET = 12:30 UTC; 7:30pm ET = 00:30 UTC next day.
AM = (12, 30, 0)
PM = (0, 30, 1)
SAT = (15, 0, 0)  # Saturday prompt, 10am ET, kept out of the time read

def ts(date, slot):
    h, m, plus = slot
    d = dt.date.fromisoformat(date) + dt.timedelta(days=plus)
    return f"{d.isoformat()} {h:02d}:{m:02d}:00+00"

def q(s): return s.replace("'", "''")

def caption(item):
    hook = item["hook"].replace("\n", " ")
    if item["kind"] == "prompt":
        return f"{hook}\n\n{item['line']}\n\nOr send this to someone and ask them.\n\n{HASHTAGS}"
    return (f"{hook}\n\n{item['line']}\n\n{item['ref']} · NLT\n\n{item['ask']}\n\n{CTA}\n\n{HASHTAGS}")

def car_caption(c):
    refs = "\n".join(f"{i}. {r}" for i, r in enumerate(c["refs"], 1))
    return f"{c['cover']}\n\n{c['line']}\n\n{refs}\n(all NLT)\n\n{c['ask']}\n\n{CTA}\n\n{HASHTAGS}"

def rows_for(weeks, slot_for):
    out = []
    for it in SLATE:
        if it["kind"] == "prompt": continue
        d = dt.date.fromisoformat(it["date"])
        wk = None
        if dt.date(2026, 11, 30) <= d <= dt.date(2026, 12, 4): wk = 1
        elif dt.date(2026, 12, 7) <= d <= dt.date(2026, 12, 11): wk = 2
        elif dt.date(2026, 12, 14) <= d <= dt.date(2026, 12, 18): wk = 3
        elif dt.date(2026, 12, 21) <= d <= dt.date(2026, 12, 25): wk = 4
        elif it["id"] == "r00_empty_chair": wk = 0
        if wk not in weeks: continue
        out.append((ts(it["date"], slot_for(wk)), "REELS", f"reels-refresh/{it['id']}.mp4", None, caption(it)))
    for c in CAROUSELS:
        d = dt.date.fromisoformat(c["date"])
        wk = 3 if d.day <= 18 else 4
        if wk not in weeks: continue
        paths = [f"carousels-refresh/{c['id']}/{c['id']}_feed_{k}.png" for k in range(len(c["refs"]) + 2)]
        out.append((ts(c["date"], slot_for(wk)), "CAROUSEL", paths[0], paths, car_caption(c)))
        # story nudge 30 min after: the 9:16 cover
        h, m, plus = slot_for(wk); m += 30
        if m >= 60: h, m = h + 1, m - 60
        out.append((ts(c["date"], (h, m, plus)), "STORIES", f"carousels-refresh/{c['id']}/{c['id']}_story_0.png", None, ""))
    if 1 in weeks or 2 in weeks:
        prompt = next(s for s in SLATE if s["kind"] == "prompt")
        for sat in ("2026-12-05", "2026-12-12"):
            out.append((ts(sat, SAT), "REELS", f"reels-refresh/{prompt['id']}.mp4", None, caption(prompt)))
    return sorted(out)

def sql(rows, header):
    vals = []
    for i, (when, mt, path, paths, cap) in enumerate(rows, 1):
        arr = "NULL" if not paths else "ARRAY[" + ",".join(f"'{p}'" for p in paths) + "]::text[]"
        vals.append(f"  ({i}, '{when}'::timestamptz, '{mt}', '{path}', {arr}, '{q(cap)}')")
    return (header + "\n"
            "with base as (select coalesce(max(day_index), 0) as m from ig_post_queue)\n"
            "insert into ig_post_queue (day_index, scheduled_for, media_type, media_path, media_paths, caption, status)\n"
            "select base.m + v.n, v.at, v.mt, v.mp, v.mps, v.cap, 'pending'\n"
            "from base, (values\n" + ",\n".join(vals) + "\n) as v(n, at, mt, mp, mps, cap);\n")

if __name__ == "__main__":
    w12 = rows_for({0, 1, 2}, lambda wk: PM if wk == 2 else AM)
    open("seed-refresh-weeks1-2.sql", "w").write(sql(w12,
        "-- Content refresh, Nov 26 - Dec 12 2026. Generated by seed_refresh_calendar.py.\n"
        "-- Week 1 reels 7:30am ET, week 2 reels 7:30pm ET (time test). Saturday prompts + Nov 26 bridge sit outside the test.\n"
        "-- All rows pending. Run AFTER uploading reels-refresh/ to the ig-media bucket."))
    win = (sys.argv[1] if len(sys.argv) > 1 else "am").lower()
    slot = PM if win == "pm" else AM
    w34 = rows_for({3, 4}, lambda wk: slot)
    open("seed-refresh-weeks3-4.sql", "w").write(sql(w34,
        f"-- Content refresh, Dec 14 - 25 2026, posting at the test winner ({win.upper()}). Generated by seed_refresh_calendar.py {win}.\n"
        "-- Regenerate with the other slot if week 2 wins. Run AFTER uploading reels-refresh/ and carousels-refresh/."))
    print(f"weeks 1-2: {len(w12)} rows   weeks 3-4 ({win}): {len(w34)} rows")
